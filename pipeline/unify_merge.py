"""Merge the unified uṣūl tables into data/usul/ (Eisa 2026-11-26).

    python3 -m pipeline.unify_merge

For every slot that is an old category's general rule (pipeline.unify_profiles.where), where the
reviewed profile (data/profiles.yaml) gives other wujūh, the reviewed wujūh are kept (`via:
reviewed`, its cite, its `option`) and the table's reading is recorded under `disagreements`:
the al-Futūḥ and al-Budūr cross-checks of 2026-11-26 sided with the reviewed table each time
(pipeline/PILOT.md). Where the reviewed ids aren't in the table's vocabulary (a finer split of the
same reading), the table stays and the pair is noted. Listed words the reviewed table rules on
are corrected the same way (KNOWN_LISTED).
"""
from __future__ import annotations

from pathlib import Path

import yaml

from mushaf_data.paths import DATA
from mushaf_data.profiles import load as reviewed
from mushaf_data.ruwat import RUWAT

from .unify_profiles import DIR, where

OUT = DATA / "usul"


class _NoAliases(yaml.SafeDumper):
    def ignore_aliases(self, data):
        return True
EVIDENCE = "al-Futūḥ's rows and al-Budūr's statements side with the reviewed table (cross-checks 2026-11-26)"
# listed words the reviewed table rules on: (category file, a word of the entry, case prefix, wujūh, cite)
KNOWN_LISTED = [("hamz_waqf", "مستهزء", "hamz_waqf_mid", ["tashil", "ibdal_ya", "hadhf"], "wafi 116, 118; budur 22; ghayth-1 31")]
HEADER = """# {cat}: one rule for all twenty ruwāt (the Shāṭibiyyah and the Durrah), from al-Wāfī and al-Īḍāḥ's
# uṣūl chapters, unified 2026-11-26 (pipeline/prompt_unify.md). Each slot cites its page; `via`:
# asl / asl_unstated = the Durrah rāwī reads as his aṣl (al-Īḍāḥ pp. 40-43); as_hafs = no row states
# it, read as Ḥafṣ (Eisa 2026-11-26); as_wasl = stops as in his waṣl; reviewed = kept from the
# reviewed profile table where a fresh reading disagreed (see `disagreements`). `open`: questions
# for Eisa. Generated by `python3 -m pipeline.unify_merge`; edit by review, then regenerate.
"""


def merge() -> dict[str, int]:
    rev = reviewed()
    tables = {f.stem: yaml.safe_load(f.read_text(encoding="utf-8")) for f in sorted(DIR.glob("*.yaml"))}
    stats = {"kept_reviewed": 0, "finer_split": 0, "listed_fixed": 0}
    for old, (c, k) in where().items():
        t = tables[c]
        vocab = {w["id"] for w in t.get("wujuh") or []}
        case = t["cases"][k]
        for r in RUWAT:
            e = rev[r].get(old)
            if not e:
                continue
            want, have = list(e["wujuh"]), list((case["ruwat"].get(r) or {}).get("wujuh") or [])
            if set(want) == set(have):
                continue
            d = {"rawi": r, "case": case.get("case"), "category": old, "table": have, "reviewed": want}
            if set(want) <= vocab:
                slot = {"wujuh": want, "cite": [str(next(iter(e["wujuh"].values()))[0])], "via": "reviewed"}
                if e.get("option"):
                    slot["option"] = True
                case["ruwat"][r] = slot
                d["kept"] = "reviewed"
                d["why"] = EVIDENCE
                stats["kept_reviewed"] += 1
            else:
                d["kept"] = "table"
                d["why"] = "the table splits the reviewed reading more finely (same reading, other ids)"
                stats["finer_split"] += 1
            t.setdefault("disagreements", []).append(d)
    for c, word, prefix, wujuh, cite in KNOWN_LISTED:
        for x in tables[c].get("listed") or []:
            if any(word in str(w) for w in x.get("words") or []) and str(x.get("case", "")).startswith(prefix):
                old = dict(x.get("ruwat") or {})
                x["ruwat"] = {**old, **{r: list(wujuh) for r in ("khalaf_an_hamzah", "khallad")}}
                x["cite"] = list(x.get("cite") or []) + [cite]
                tables[c].setdefault("disagreements", []).append(
                    {"words": x.get("words"), "table": old, "reviewed": wujuh, "kept": "reviewed", "why": EVIDENCE})
                stats["listed_fixed"] += 1
    OUT.mkdir(parents=True, exist_ok=True)
    for c, t in tables.items():
        t["status"] = "merged 2026-11-26; open questions for review" if t.get("open") else "merged 2026-11-26"
        (OUT / f"{c}.yaml").write_text(HEADER.format(cat=c) + yaml.dump(t, Dumper=_NoAliases, allow_unicode=True, sort_keys=False, width=140),
                                       encoding="utf-8")
    return stats


def main():
    print(merge(), "→", OUT)


if __name__ == "__main__":
    main()
